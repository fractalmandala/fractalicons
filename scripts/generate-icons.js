import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const packageDir = path.resolve(__dirname, '..');

// Support both 'src/lib/icons' and 'src/lib/iconsets'
const iconsDir = path.join(packageDir, 'src/lib/icons');
const iconsetsDir = path.join(packageDir, 'src/lib/iconsets');
const sourceDir = fs.existsSync(iconsDir) ? iconsDir : iconsetsDir;
const libDir = path.join(packageDir, 'src/lib');
const lockPath = path.join(packageDir, '.generate-icons.lock');
const packageTempDir = path.join(packageDir, '.svelte-kit/__package__');

const generatedHeader = '// Generated by scripts/generate-icons.js. Do not edit by hand.\n';
const hardcodedCurrentColorCandidates = [
	'#000',
	'#000000',
	'#0f172a',
	'#111',
	'#111111',
	'#1f2937',
	'black',
	'rgb(0,0,0)',
	'rgb(0, 0, 0)'
];

const presentationAttrNames = [
	'fill',
	'stroke',
	'stroke-width',
	'stroke-linecap',
	'stroke-linejoin',
	'stroke-miterlimit',
	'stroke-dasharray',
	'stroke-dashoffset',
	'stroke-opacity',
	'fill-rule',
	'fill-opacity',
	'clip-rule'
];

export const familyPrefixMap = {
	anticons: 'an',
	boxicons: 'bo',
	fontawesome: 'fa',
	iconoir: 'ic',
	iconoirfill: 'icf',
	lucide: 'lu',
	lucidenim: 'lua',
	lucideanim: 'lua',
	materialanim: 'maa',
	phosphor: 'ph',
	phosphorfill: 'phf',
	remix: 're',
	remixfill: 'ref'
};

function safeRemove(targetPath) {
	if (fs.existsSync(targetPath)) {
		fs.rmSync(targetPath, { recursive: true, force: true, maxRetries: 10, retryDelay: 50 });
	}
}

function getPrefix(setName) {
	return familyPrefixMap[setName] || setName;
}

function toIdentifierPart(value) {
	return value
		.split(/[^a-zA-Z0-9]+/)
		.filter(Boolean)
		.map((part) => part.charAt(0).toUpperCase() + part.slice(1))
		.join('');
}

function toNamedExport(setName, iconName) {
	const prefix = getPrefix(setName);
	const name = `${prefix}-${iconName}`;
	const identifier = name.charAt(0).toLowerCase() + toIdentifierPart(name).slice(1);

	return /^[0-9]/.test(identifier) ? `icon${identifier}` : identifier;
}

function toFullNameExport(setName, iconName) {
	const name = `${setName}-${iconName}`;
	const identifier = name.charAt(0).toLowerCase() + toIdentifierPart(name).slice(1);

	return /^[0-9]/.test(identifier) ? `icon${identifier}` : identifier;
}

function toSafePathName(filename) {
	return filename.replace(/\.svg$/i, '').toLowerCase();
}

function extractViewBox(svg) {
	const vbMatch = svg.match(/<svg[^>]*\bviewBox="([^"]+)"/i);
	if (vbMatch) return vbMatch[1];

	const widthMatch = svg.match(/<svg[^>]*\bwidth="([0-9.]+)(?:px)?"/i);
	const heightMatch = svg.match(/<svg[^>]*\bheight="([0-9.]+)(?:px)?"/i);
	if (widthMatch && heightMatch) {
		return `0 0 ${widthMatch[1]} ${heightMatch[1]}`;
	}

	return '0 0 24 24';
}

function normalizeColor(svg) {
	let result = svg;

	for (const color of hardcodedCurrentColorCandidates) {
		result = result
			.replaceAll(`fill="${color}"`, 'fill="currentColor"')
			.replaceAll(`stroke="${color}"`, 'stroke="currentColor"')
			.replaceAll(`fill:${color}`, 'fill:currentColor')
			.replaceAll(`stroke:${color}`, 'stroke:currentColor');
	}

	return result;
}

function stripSvg(svg) {
	const svgTagMatch = svg.match(/<svg\b([^>]*)>/i);
	const rootAttrs = svgTagMatch ? svgTagMatch[1] : '';

	const collectedAttrs = [];
	for (const attr of presentationAttrNames) {
		const match = rootAttrs.match(new RegExp(`\\b${attr}="([^"]*)"`, 'i'));
		if (match) {
			collectedAttrs.push(`${attr}="${match[1]}"`);
		}
	}

	// Remove XML declarations, DOCTYPEs, and comments
	let cleaned = svg
		.replace(/<\?xml[^>]*\?>/gi, '')
		.replace(/<!DOCTYPE[^>]*>/gi, '')
		.replace(/<!--[\s\S]*?-->/g, '');

	// Strip outer <svg ...> and </svg>
	cleaned = cleaned.replace(/^[\s\S]*?<svg[^>]*>/i, '').replace(/<\/svg>[\s\S]*$/i, '');

	// Remove invisible spacer rects (fill="none" with no stroke)
	cleaned = cleaned.replace(/<rect\b(?![^>]*\bstroke=)[^>]*\bfill="none"[^>]*\/?>(\s*<\/rect>)?/gi, '');

	let inner = normalizeColor(cleaned.trim());

	// If root <svg> had presentation attributes (e.g. fill="none" stroke="currentColor" stroke-width="2"),
	// wrap in a <g> tag to preserve stroke/fill styling
	if (collectedAttrs.length > 0) {
		const attrStr = normalizeColor(collectedAttrs.join(' '));
		inner = `<g ${attrStr}>${inner}</g>`;
	}

	return inner;
}

function cleanGeneratedSet(setName) {
	const setDir = path.join(libDir, setName);
	const setBarrel = path.join(libDir, `${setName}.ts`);

	safeRemove(setDir);
	safeRemove(setBarrel);
}

function writeIconModule(setName, iconName, svg) {
	const setDir = path.join(libDir, setName);
	const modulePath = path.join(setDir, `${iconName}.ts`);
	const exportName = toNamedExport(setName, iconName);
	const fullAliasName = toFullNameExport(setName, iconName);
	const viewBox = extractViewBox(svg);
	const body = stripSvg(svg);

	fs.mkdirSync(setDir, { recursive: true });

	const aliasLine =
		fullAliasName !== exportName ? `\nexport { ${exportName} as ${fullAliasName} };` : '';

	fs.writeFileSync(
		modulePath,
		`${generatedHeader}import type { IconData } from '../types.js';\n\nconst ${exportName} = ${JSON.stringify(
			{
				name: iconName,
				set: setName,
				viewBox,
				body
			},
			null,
			'\t'
		)} as const satisfies IconData;\n\nexport default ${exportName};\nexport { ${exportName} };${aliasLine}\n`,
		'utf8'
	);

	return { exportName, fullAliasName, iconName };
}

function writeSetBarrel(setName, icons) {
	const lines = icons.map(({ exportName, fullAliasName, iconName }) => {
		if (fullAliasName && fullAliasName !== exportName) {
			return `export { default as ${exportName}, ${fullAliasName} } from './${setName}/${iconName}.js';`;
		}
		return `export { default as ${exportName} } from './${setName}/${iconName}.js';`;
	});

	fs.writeFileSync(path.join(libDir, `${setName}.ts`), `${generatedHeader}${lines.join('\n')}\n`, 'utf8');
}

if (!fs.existsSync(sourceDir)) {
	console.log(`No icons directory found at ${sourceDir}`);
	process.exit(0);
}

try {
	fs.writeFileSync(lockPath, String(process.pid), { flag: 'wx' });
} catch {
	console.error('Icon generation is already running.');
	process.exit(1);
}

// Clean any leftover build cache to prevent ENOTEMPTY in @sveltejs/package
safeRemove(packageTempDir);

const startTime = Date.now();
const setNames = fs
	.readdirSync(sourceDir, { withFileTypes: true })
	.filter((entry) => entry.isDirectory())
	.map((entry) => entry.name)
	.sort();

let totalIcons = 0;
let totalSets = 0;

try {
	for (const setName of setNames) {
		const setSourceDir = path.join(sourceDir, setName);
		const svgFiles = fs
			.readdirSync(setSourceDir, { withFileTypes: true })
			.filter((entry) => entry.isFile() && entry.name.endsWith('.svg'))
			.map((entry) => entry.name)
			.sort();

		if (svgFiles.length === 0) {
			console.log(`${setName}: skipped (0 SVGs found)`);
			continue;
		}

		cleanGeneratedSet(setName);

		const icons = svgFiles.map((file) => {
			const iconName = toSafePathName(file);
			const svg = fs.readFileSync(path.join(setSourceDir, file), 'utf8');

			return writeIconModule(setName, iconName, svg);
		});

		writeSetBarrel(setName, icons);
		totalIcons += icons.length;
		totalSets++;
		console.log(`${setName} (${getPrefix(setName)}): generated ${icons.length} icons`);
	}

	// Pre-clean .svelte-kit/__package__ so svelte-package never hits ENOTEMPTY on macOS APFS
	safeRemove(packageTempDir);

	const elapsed = ((Date.now() - startTime) / 1000).toFixed(2);
	console.log(`\nSuccessfully generated ${totalIcons} icons across ${totalSets} sets in ${elapsed}s.`);
} finally {
	fs.rmSync(lockPath, { force: true });
}
