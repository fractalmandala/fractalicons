#!/usr/bin/env node
// Drives the harness in Chrome.
//   node run.mjs survey    [--only a,b]   structure of every icon in every family   -> out/survey.json
//   node run.mjs templates [--only a,b]   the 22 templates on a sample per family    -> out/templates.json (and out/props.json)
import { createServer } from 'vite';
import { chromium } from 'playwright-core';
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../..');
const out = join(here, 'out');
const mode = process.argv[2];
const onlyArg = process.argv.indexOf('--only');
const only = onlyArg === -1 ? null : process.argv[onlyArg + 1].split(',');
const families = Object.keys(JSON.parse(readFileSync(join(repo, 'sources.json'), 'utf8')).icons).filter((f) => !only || only.includes(f));
const sampleOf = Object.fromEntries(JSON.parse(readFileSync(join(repo, 'apps/icons-docs/src/lib/data/families.json'), 'utf8')).families.map((f) => [f.slug, f.sample.name]));
const N_RANDOM = Number(process.env.N_RANDOM ?? 10);

mkdirSync(out, { recursive: true });

// the harness imports each family by name; written here from sources.json so a clean checkout works
writeFileSync(join(here, 'src/loaders.js'), `// Generated by run.mjs from sources.json. Do not edit by hand.\nexport const loaders = {\n${Object.keys(JSON.parse(readFileSync(join(repo, 'sources.json'), 'utf8')).icons).map((f) => `\t${f}: () => import('@fractaldesign/icons/${f}')`).join(',\n')}\n};\n`);

const server = await createServer({ root: here, logLevel: 'error' });

await server.listen();

const browser = await chromium.launch({ executablePath: process.env.CHROME ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
const page = await browser.newPage({ viewport: { width: 400, height: 300 } });

page.setDefaultTimeout(0);
page.on('pageerror', (e) => console.log('pageerror', String(e).slice(0, 200)));
await page.exposeFunction('__progress', (msg) => process.stdout.write(`\r${msg}`.padEnd(60)));
await page.goto('http://localhost:5199/');
await page.waitForFunction(() => window.__ready === true);

const load = (file) => (existsSync(join(out, file)) ? JSON.parse(readFileSync(join(out, file), 'utf8')) : {});
const started = Date.now();

try {
	if (mode === 'survey') {
		const all = load('survey.json');

		for (const slug of families) {
			const t = Date.now();

			all[slug] = await page.evaluate((s) => window.census.survey(s, window.__progress), slug);
			console.log(`\r${slug.padEnd(18)} ${all[slug].count} icons in ${((Date.now() - t) / 1000).toFixed(1)}s`);
			writeFileSync(join(out, 'survey.json'), JSON.stringify(all));
		}
	} else if (mode === 'templates') {
		const survey = load('survey.json');
		const all = load('templates.json');
		const props = load('props.json');

		for (const slug of families) {
			const rows = survey[slug].rows;
			const sampleName = sampleOf[slug];
			const picks = [];
			const used = new Set();
			const add = (i, why) => {
				if (i == null || used.has(i)) return;

				used.add(i);
				picks.push({ i, why });
			};

			add(rows.find((r) => r.name === sampleName)?.i, 'sample');
			add([...rows].filter((r) => r.f.shapes > 0).sort((a, b) => b.f.shapes - a.f.shapes)[0]?.i, 'most shapes');

			// the rest: seeded, so a run can be repeated
			let seed = [...slug].reduce((h, c) => (h * 31 + c.charCodeAt(0)) >>> 0, 7);
			const next = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 2 ** 32);

			while (picks.length < 2 + N_RANDOM) add(Math.floor(next() * rows.length), 'random');

			const t = Date.now();

			all[slug] = await page.evaluate(([s, p, n]) => window.census.templatesFor(s, p, n, window.__progress), [slug, picks, sampleName]);
			props[slug] = await page.evaluate(([s, i]) => window.census.propsFor(s, i), [slug, picks[0].i]);
			console.log(`\r${slug.padEnd(18)} ${picks.length} icons × ${all[slug].rows[0] ? Object.keys(all[slug].rows[0].cases).length : 0} templates in ${((Date.now() - t) / 1000).toFixed(1)}s`);
			writeFileSync(join(out, 'templates.json'), JSON.stringify(all));
			writeFileSync(join(out, 'props.json'), JSON.stringify(props));
		}
	} else if (mode === 'targeted') {
		// the icons the random sample may have missed: shapes with their own transform, and layers faded with opacity
		const survey = load('survey.json');
		const all = load('targeted.json');

		for (const slug of families) {
			const rows = survey[slug].rows;
			const picks = [
				...rows.filter((r) => r.f.selfTransformedShapes > 0).slice(0, 6).map((r) => ({ i: r.i, why: 'own transform' })),
				...rows.filter((r) => r.f.ownFaded > 0 && !(r.f.selfTransformedShapes > 0)).slice(0, 6).map((r) => ({ i: r.i, why: 'own opacity' })),
				...rows.filter((r) => r.f.alphaPaint > 0 && !(r.f.ownFaded > 0) && !(r.f.selfTransformedShapes > 0)).slice(0, 6).map((r) => ({ i: r.i, why: 'paint alpha' }))
			];

			if (!picks.length) continue;

			all[slug] = await page.evaluate(([s, p, n]) => window.census.templatesFor(s, p, n), [slug, picks, sampleOf[slug]]);
			process.stdout.write(`targeted ${slug}: ${picks.length} icons\n`);
			writeFileSync(join(out, 'targeted.json'), JSON.stringify(all));
		}
	} else {
		console.error('usage: run.mjs survey|templates|targeted [--only a,b]');
		process.exitCode = 2;
	}
} finally {
	await browser.close();
	await server.close();
	console.log(`done in ${((Date.now() - started) / 1000).toFixed(0)}s`);
}
